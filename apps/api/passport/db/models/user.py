"""User models (DB_MODEL.md 4.1).

Withdrawal physically deletes the users row. Every FK that points at users is
ON DELETE CASCADE, so all direct and indirect children go with it in the same
transaction (DB_MODEL.md 6.1, 9.2). Shared parents (tenants, OIDC
configurations) are never deleted.
"""

import uuid
from collections.abc import Mapping
from datetime import datetime
from enum import IntEnum
from typing import Any

from sqlalchemy import ForeignKey, String, Text, UniqueConstraint, false, func, text
from sqlalchemy.orm import Mapped, mapped_column

from passport.db.base import Base, IntEnumType


class UserStatus(IntEnum):
    """Account status stored in users.user_status.

    The DB stores the smallint key and the API exposes the member name. Keys
    are permanent: never renumber them, and never reuse the retired key 5.

    Transitions (DB_MODEL.md 5.1):
    - PENDING_VERIFICATION -> ACTIVE when the signup email is confirmed.
      Accounts created through OIDC start as ACTIVE.
    - ACTIVE, SUSPENDED and DEACTIVATED change among themselves only by a
      platform admin (updateUserStatus). Leaving ACTIVE ends every login of
      the user with LoginEndReason.ACCOUNT_INACTIVE.
    - Withdrawal deletes the row instead of switching to a status.
    """

    PENDING_VERIFICATION = 1  # Local signup waiting for email confirmation.
    ACTIVE = 2
    SUSPENDED = 3
    DEACTIVATED = 4


class PasswordAlgorithm(IntEnum):
    """Hash algorithm of user_securities.password_hash.

    The application checks that this key matches the algorithm named in the
    PHC string before it trusts the hash.
    """

    ARGON2ID = 1  # Argon2id PHC string (NFR-SEC-005).


class User(Base):
    """Global Passport account: immutable ID, account status and profile.

    One account serves every tenant and SaaS application. user_securities,
    identities and tenant_memberships all hang off this row.

    - A UserSecurity row is always created in the same transaction.
    - Withdrawal deletes this row and its FK children (see module docstring).
      audit_logs keep the former user_id without personal data, and the ID
      is never issued again.
    - No DB CHECK constraints (DB_MODEL.md 1): status and value formats are
      validated by the application.
    - Never expose the row as-is. DTOs map the fields allowed for the caller's
      role and tenant explicitly (FR-USER-007).
    """

    __tablename__ = "users"
    # eager_defaults: RETURNING the onupdate timestamp; async sessions cannot lazy-load it.
    __mapper_args__: Mapping[str, Any] = {"eager_defaults": True}

    # UUIDv7 generated by the application: time-ordered for index locality.
    user_id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid7)
    # Local signup starts here; OIDC account creation sets ACTIVE explicitly.
    user_status: Mapped[UserStatus] = mapped_column(
        IntEnumType(UserStatus),
        server_default=text(str(UserStatus.PENDING_VERIFICATION.value)),
    )
    is_system: Mapped[bool] = mapped_column(server_default=false())
    # P0: set only by the install CLI. Exposed in the API as platform_roles.
    is_platform_admin: Mapped[bool] = mapped_column(server_default=false())
    # Lower-case normalized and validated by the application; API field "email".
    # It is the Local login ID (FR-AUTH-001) and blocks a second account with
    # the same address (D-08), but never links external identities. Withdrawal
    # frees it, so the same address can sign up again under a new user_id.
    user_email: Mapped[str] = mapped_column(String(254), unique=True)
    display_name: Mapped[str] = mapped_column(String(50))
    # Optional given name. Column name kept as specified in DB_MODEL.md.
    fist_name: Mapped[str | None] = mapped_column(String(50))
    # Optional family name. Both name columns follow the real-name view rights.
    last_name: Mapped[str | None] = mapped_column(String(50))
    # Local: when the confirmation link was used. OIDC: when the provider
    # asserted email_verified = true. NULL means not verified.
    email_verified_at: Mapped[datetime | None]
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    # Refreshed by the ORM on every UPDATE of the row.
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now()
    )
    # Optional link to a record in another system: its ID and where it lives.
    external_id: Mapped[str | None] = mapped_column(String(50))
    external_source: Mapped[str | None] = mapped_column(String(50))


class UserSecurity(Base):
    """Local password credential, login statistics and Local lockout state.

    Kept apart from users so profile reads never touch secrets. Exactly one
    row per user, created in the same transaction as the user. OIDC-only
    accounts have a row too, with every password column NULL.

    - password_hash IS NULL means the user has no Local credential, and the
      password APIs answer 409 local_credential_not_set.
    - A failed Local login or password reauthentication atomically updates
      failed_login_count, last_failed_login_at, locked_until and updated_at,
      and commits before the failure response. Never roll it back.
    - A successful Local login or reauthentication resets failed_login_count
      to 0 and locked_until to NULL. OIDC logins leave these columns alone.
    - A password change updates the hash, algorithm and change time, clears
      must_change_password and the failure state, and ends all of the user's
      logins, all in one transaction.
    - Concurrent writers lock the row (FOR UPDATE) or use one atomic UPDATE.
    - Never map this row to a general user DTO.
    """

    __tablename__ = "user_securities"
    __mapper_args__: Mapping[str, Any] = {"eager_defaults": True}

    # PK and FK: exactly one row per user, deleted with the user.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.user_id", ondelete="CASCADE"), primary_key=True
    )
    # The three password columns are set together or are all NULL (no Local
    # credential); the application enforces this.
    password_hash: Mapped[str | None] = mapped_column(Text)
    password_changed_at: Mapped[datetime | None]
    # Must match the algorithm in the PHC string of password_hash.
    password_algorithm: Mapped[PasswordAlgorithm | None] = mapped_column(
        IntEnumType(PasswordAlgorithm)
    )
    # Password change required; cleared by a successful password change.
    must_change_password: Mapped[bool] = mapped_column(server_default=false())
    # Consecutive Local login/reauth failures since the last success. Not the
    # 15-minute window or per-IP counters, which live in Valkey.
    failed_login_count: Mapped[int] = mapped_column(server_default=text("0"))
    # Kept as history after a successful login.
    last_failed_login_at: Mapped[datetime | None]
    # Last Local or OIDC login that created a logins row. Reauthentication,
    # token refresh and SSO session reuse do not update it.
    last_login_at: Mapped[datetime | None]
    # Local password lockout expiry; NULL or a past time means unlocked.
    # Requests during a lockout do not extend it, and it never blocks OIDC.
    locked_until: Mapped[datetime | None]
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now()
    )


class Identity(Base):
    """External OIDC identity (issuer, subject) linked to a Passport user.

    Maps an external authentication result to the global user and records the
    tenant and OIDC configuration used for the link. Identities are matched
    only by (issuer, subject), never merged by email (FR-OIDC-004, 005, D-08).
    When two first logins race, the loser fails the UNIQUE constraint, rolls
    back and continues with the existing identity.

    listMyIdentities combines these rows with whether a Local password exists
    (user_securities.password_hash); the hash itself is never returned.
    """

    __tablename__ = "identities"
    __table_args__ = (
        UniqueConstraint("issuer", "subject", name="uq_identities_issuer_subject"),
    )

    identity_id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid7)
    # Indexed for listMyIdentities; deleted with the user.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.user_id", ondelete="CASCADE"), index=True
    )
    # OIDC issuer URL as found in the ID Token "iss" claim.
    issuer: Mapped[str] = mapped_column(String(2048))
    # ID Token "sub" claim: the user's ID at the issuer.
    subject: Mapped[str] = mapped_column(String(255))
    # Tenant whose OIDC configuration was used to link this identity.
    tenant_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("tenants.tenant_id", ondelete="RESTRICT")
    )
    config_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("tenant_oidc_configurations.config_id", ondelete="RESTRICT")
    )
    linked_at: Mapped[datetime] = mapped_column(server_default=func.now())
    last_used_at: Mapped[datetime | None]


class EmailVerificationToken(Base):
    """Current one-time email verification token of a Local signup.

    At most one row per user (user_id is the PK); no issue history is kept.
    OIDC-only users and users who already verified have no row. Expired rows
    are purged by a periodic cleanup job (DB_MODEL.md 9.1).

    - Resend: lock the users row FOR UPDATE, check that the account is still
      an unverified Local signup, then UPSERT by user_id. The previous token
      stops working at once.
    - Confirm: find user_id by token_hash, lock the users row FOR UPDATE and
      recheck, then consume once with DELETE ... WHERE user_id = :user_id AND
      token_hash = :token_hash AND expires_at > now() RETURNING user_id. Set
      users.email_verified_at and user_status = ACTIVE in the same
      transaction; on failure the delete rolls back too.
    """

    __tablename__ = "email_verification_tokens"

    # PK and FK: at most one token per user, deleted with the user.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.user_id", ondelete="CASCADE"), primary_key=True
    )
    # SHA-256 (32 bytes) of the raw token. The raw token is never stored.
    token_hash: Mapped[bytes] = mapped_column(unique=True)
    # Proposed: 24 hours after issue.
    expires_at: Mapped[datetime]
    # Issue time of the current token. The server default covers INSERT only,
    # so a resend UPSERT must set it explicitly.
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
